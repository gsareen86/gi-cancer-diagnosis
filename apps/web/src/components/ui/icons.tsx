import type { SVGProps } from 'react';

/**
 * The icon set.
 *
 * Inline SVG rather than a package: an icon library is 40kB of JavaScript to draw shapes that do
 * not change, on an interface whose users are on patchy mobile data, and every one of them would
 * need auditing against the Content Security Policy anyway.
 *
 * Every icon is `aria-hidden`. None of them is ever the only thing conveying a meaning — the
 * bell has a count, the risk edge has a word, the chevron has a labelled control around it — so
 * there is nothing for a screen reader to gain by announcing "path".
 */

type IconProps = Omit<SVGProps<SVGSVGElement>, 'children'> & { className?: string };

