import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdirSync, readFileSync } from 'node:fs';
import { BASE, fixtureCode } from './support/local-fixture.mjs';

// Credentials come only from the ignored, local fictional fixture. No real accounts or release.
const fixture = JSON.parse(readFileSync('var/tmp/clinical-fixture.json', 'utf8'));
const text = JSON.parse(readFileSync('apps/web/messages/en.json', 'utf8'));
const out = 'var/tmp/early-care-screenshots';
mkdirSync(out, { recursive: true });
const browser = await chromium.launch(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {});
const errors = [];
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  context.on('page', page => page.on('pageerror', error => errors.push(error.message)));
  const page = await context.newPage();
  const path = `/doctor/case/${fixture.caseId}`;
  const endpoint = `/api/doctor/cases/${fixture.caseId}`;
  await page.goto(BASE + '/login?next=' + encodeURIComponent(path));
  await page.locator('#email').fill(fixture.doctor.email);
  await page.locator('#password').fill(fixture.password);
  await page.locator('button[type=submit]').click();
  await page.waitForURL('**/mfa?**');
  await page.locator('#code').fill(fixtureCode());
  await page.locator('button[type=submit]').click();
  await page.waitForURL(BASE + path);
  await page.getByRole('heading', { name: text.doctor.briefTitle, exact: true }).waitFor();
  const before = await page.evaluate(async url => (await fetch(url)).json(), endpoint);
  assert.equal(before.review, null, 'Opening a case must not start review');
  assert.ok(before.brief.facts.some(f => f.questionId === 'history.medications' && f.answer.includes('Ibuprofen')));
  await page.screenshot({ path: out + '/doctor-brief-desktop.png', fullPage: true });
  const stale = await context.newPage();
  await stale.goto(BASE + path);
  await stale.getByRole('tab', { name: text.doctor.panelReview, exact: true }).click();
  await page.getByRole('button', { name: text.doctor.startReview, exact: true }).click();
  await page.getByRole('button', { name: text.doctor.startReview, exact: true }).waitFor({ state: 'hidden' });
  await page.getByRole('tab', { name: text.doctor.panelReview, exact: true }).click();
  const saving = page.waitForResponse(r => r.url().endsWith(endpoint + '/review') && r.request().method() === 'PUT');
  await page.locator('#notes').fill('Synthetic preserved physician draft. Not medical advice.');
  const saved = await saving;
  assert.equal(saved.status(), 200);
  assert.equal((await saved.json()).draftRevision, 1);
  await page.reload();
  await page.getByRole('tab', { name: text.doctor.panelReview, exact: true }).click();
  assert.equal(await page.locator('#notes').inputValue(), 'Synthetic preserved physician draft. Not medical advice.');
  const conflict = stale.waitForResponse(r => r.url().endsWith(endpoint + '/review') && r.request().method() === 'PUT');
  await stale.locator('#notes').fill('Synthetic stale-tab draft that must be preserved locally.');
  assert.equal((await conflict).status(), 409);
  await stale.getByRole('alert').filter({ hasText: text.error.draft_conflict }).waitFor();
  assert.equal(await stale.locator('#notes').inputValue(), 'Synthetic stale-tab draft that must be preserved locally.');
  await stale.screenshot({ path: out + '/draft-conflict-desktop.png', fullPage: true });
  await page.goto(BASE + '/doctor/triage');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('link', { name: text.doctor.openReview, exact: true }).waitFor();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Queue must not overflow mobile');
  assert.equal(await page.locator('#triage-filters').isVisible(), false);
  await page.screenshot({ path: out + '/doctor-queue-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: out + '/doctor-queue-desktop.png', fullPage: true });

  const patientContext = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const patient = await patientContext.newPage();
  patient.on('pageerror', error => errors.push(error.message));
  await patient.goto(BASE + '/login?next=' + encodeURIComponent('/patient/dashboard'));
  await patient.locator('#email').fill(fixture.patient.email);
  await patient.locator('#password').fill(fixture.password);
  await patient.locator('button[type=submit]').click();
  await patient.waitForURL('**/patient/dashboard');
  const created = await patient.evaluate(async () => {
    const response = await fetch('/api/cases', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ entryPointId: 'ep_pain' }) });
    return { status: response.status, body: await response.json() };
  });
  assert.equal(created.status, 201);
  await patient.goto(BASE + '/patient/intake/' + created.body.case.id);
  await patient.locator('[data-question-id]').waitFor();
  await patient.screenshot({ path: out + '/patient-intake-desktop.png', fullPage: true });
  await patient.setViewportSize({ width: 390, height: 844 });
  assert.ok(await patient.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await patient.screenshot({ path: out + '/patient-intake-mobile.png', fullPage: true });
  assert.deepEqual(errors, []);
  console.log('Fictional browser checks passed: explicit review start, history brief, autosave reload, stale-tab conflict, and desktop/mobile layouts.');
} finally { await browser.close(); }
